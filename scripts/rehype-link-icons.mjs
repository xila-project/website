// Adds the link convention of src/styles/xila.css to the links of the
// Markdown content: one signal per kind, never more than one icon per link.
//
//   - a link to source code on GitHub, that is a URL of the form
//     https://github.com/xila-project/<repository>/blob/... or /tree/...,
//     gets the `source-reference-link` class (GitHub icon) and the visually
//     hidden text "(source on GitHub)";
//   - any other external link gets the `external-reference-link` class
//     (external link icon) and the hidden text "(external site)";
//   - a link to another page of the site is unchanged.
//
// The `CodeReference` and `Api` components carry the same classes and hidden
// texts themselves; this plugin only handles the links written in Markdown.

// Matches the source links of the Xila repositories, as generated by
// scripts/source-reference.mjs.
const GITHUB_SOURCE =
  /^https:\/\/github\.com\/xila-project\/[^/]+\/(?:blob|tree)\//;
const EXTERNAL = /^https?:\/\//;

export const SOURCE_LINK_CLASS = "source-reference-link";
export const EXTERNAL_LINK_CLASS = "external-reference-link";
export const SOURCE_LINK_HIDDEN_TEXT = "(source on GitHub)";
export const EXTERNAL_LINK_HIDDEN_TEXT = "(external site)";

function hiddenText(value) {
  return {
    type: "element",
    tagName: "span",
    properties: { className: ["sr-only"] },
    children: [{ type: "text", value }],
  };
}

function visit(node) {
  if (node.type === "element" && node.tagName === "a") {
    const href = node.properties?.href;
    if (typeof href === "string" && EXTERNAL.test(href)) {
      const githubSource = GITHUB_SOURCE.test(href);
      const className = githubSource ? SOURCE_LINK_CLASS : EXTERNAL_LINK_CLASS;
      const text = githubSource
        ? SOURCE_LINK_HIDDEN_TEXT
        : EXTERNAL_LINK_HIDDEN_TEXT;
      node.properties.className = [
        ...(node.properties.className ?? []),
        className,
      ];
      node.children.push(hiddenText(text));
    }
  }
  node.children?.forEach(visit);
}

export function rehypeLinkIcons() {
  return (tree) => {
    visit(tree);
  };
}
