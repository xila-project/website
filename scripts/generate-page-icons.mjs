// Generates src/styles/page-icons.css: one icon per page, drawn with CSS
// masks from Starlight's built-in icon set, so nothing is added at runtime.
// The same icon marks a page in the sidebar, on link cards pointing to it,
// and in "Related documentation" / "Next steps" cards. Re-run after changing
// the map in scripts/page-icons.mjs:
//
//   node scripts/generate-page-icons.mjs && npx prettier --write src/styles/page-icons.css
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { groups, links } from "./page-icons.mjs";

// Starlight does not export its icon map, so load the module file directly.
const { Icons } = await import(
  new URL(
    "../node_modules/@astrojs/starlight/dist/components-internals/Icons.js",
    import.meta.url,
  ).href
);

const maskImage = (name) => {
  const svg = Icons[name];
  if (!svg) throw new Error(`Unknown Starlight icon: ${name}`);
  const markup = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'>${svg}</svg>`;
  // Minimal escaping keeps the data URI about a third smaller than
  // encodeURIComponent; browsers accept the remaining characters.
  const escaped = markup
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/#/g, "%23");
  return `url("data:image/svg+xml,${escaped}")`;
};

const pages = { ...links, ...groups };
const slug = (icon) => `--xila-icon-${icon.replace(/[^a-z0-9]+/gi, "-")}`;

// Content links may omit the trailing slash or point at an anchor.
const anyForm = (href) => {
  const bare = href.replace(/\/$/, "");
  return `:is([href="${href}"], [href="${bare}"], [href^="${href}#"], [href^="${bare}#"])`;
};

const related =
  ".sl-markdown-content .sl-heading-wrapper:has(> :is(#related-documentation, #next-steps)) + ul > li > a:first-child";
const contexts = {
  sidebar: (href) =>
    `.sidebar-content :is(a.entry-link, a.group-link)[href="${href}"]::before`,
  linkCard: (href) =>
    `.sl-markdown-content .sl-link-card:has(> .stack > a${anyForm(href)})::before`,
  relatedCard: (href) => `${related}${anyForm(href)}::before`,
};
const selectorsFor = (context) => Object.keys(pages).map(contexts[context]);
const list = (selectors) => selectors.join(",\n");

// Every card gets an icon so titles line up: pages use their own icon,
// GitHub links the GitHub mark, and anything else a generic document.
const fallback = { default: "document", github: "github" };
// The link convention of src/styles/xila.css draws these two icons after
// source links on GitHub and other external links.
const linkIcons = ["external", "github"];
const icons = [
  ...new Set([
    ...Object.values(pages),
    ...Object.values(fallback),
    ...linkIcons,
  ]),
];
const linkCard = ".sl-markdown-content .sl-link-card";

const css = `/* Generated by scripts/generate-page-icons.mjs; edit the map in scripts/page-icons.mjs. */

:root {
${icons.map((icon) => `  ${slug(icon)}: ${maskImage(icon)};`).join("\n")}
}

${list([...selectorsFor("sidebar"), `${linkCard}::before`, `${related}::before`])} {
  content: "";
  display: inline-block;
  flex-shrink: 0;
  width: 1rem;
  height: 1rem;
  vertical-align: -0.2em;
  background-color: currentColor;
  mask: no-repeat center / contain;
}

/* Link cards: the icon sits in its own column before the title. */
${linkCard} {
  grid-template-columns: auto 1fr auto;
}

${linkCard}::before {
  width: 1.25rem;
  height: 1.25rem;
  margin-top: 0.125rem;
  color: var(--foreground);
}

/* Related cards: the icon leads the title line. */
${related}::before {
  margin-inline-end: 0.5rem;
}

/* Fallbacks, overridden by the page icons below. */
${linkCard}::before,
${related}::before {
  mask-image: var(${slug(fallback.default)});
}

${linkCard}:has(> .stack > a[href^="https://github.com/"])::before,
${related}[href^="https://github.com/"]::before {
  mask-image: var(${slug(fallback.github)});
}
${Object.entries(pages)
  .map(
    ([href, icon]) =>
      `\n${list(Object.values(contexts).map((context) => context(href)))} {\n  mask-image: var(${slug(icon)});\n}`,
  )
  .join("\n")}
`;

writeFileSync(
  fileURLToPath(new URL("../src/styles/page-icons.css", import.meta.url)),
  css,
);
console.log(`Wrote icons for ${Object.keys(pages).length} pages.`);
